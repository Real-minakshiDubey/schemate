def ask(prompt):
    r = client.models.generate_content(model="gemini-2.5-flash", contents=prompt)
    return r.text

def ask_with_context(question):
    prompt = (
        "Neeche diye gaye text se hi jawab do. "
        "Agar jawab text mein na ho to bolo: 'mere paas is baare mein jankari nahi hai.'\n\n"
        f"Text:\n{CONTEXT}\n\nSawal: {question}"
    )
    return ask(prompt)

q_in_context = "Ladli Behna yojana mein kitne paise milte hain?"
q_not_in_context = "Is yojana ki application ki last date kya hai?"
q_tricky = "Aavedan ki antim tithi kya hai?"
print("--- Exp 1: bina context ---")
print(ask(q_in_context))

print("\n--- Exp 2: context ke saath ---")
print(ask_with_context(q_in_context))

print("\n--- Exp 3: jawab context mein nahi hai ---")
print(ask_with_context(q_not_in_context))

print("\n--- Exp 3b: tricky ---")
print(ask_with_context(q_tricky))